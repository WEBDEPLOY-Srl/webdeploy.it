// Turns the Content-Security-Policy that SvelteKit puts in each prerendered
// page into an nginx `map` file, so nginx can send the same policy as a header.
//
// Hash mode gives every page its own script hashes (the inline bootstrap
// script differs per page), so one fixed header cannot work. The meta tag stays
// in the page too; browsers enforce both, and they are identical.
//
// Usage: node scripts/nginx-csp.mjs <build-dir> <output-file>
// The output is included by nginx.conf inside `map $uri $csp { ... }`.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const META = /<meta\s+http-equiv="content-security-policy"\s+content="([^"]*)"\s*\/?>/i;

/** The policy in a page's CSP meta tag, or null if it has none. */
export function extractPolicy(html) {
	const match = META.exec(html);
	if (!match) return null;
	return match[1]
		.replaceAll('&amp;', '&')
		.replaceAll('&quot;', '"')
		.replaceAll('&#39;', "'")
		.replaceAll('&lt;', '<')
		.replaceAll('&gt;', '>');
}

/** One `map` line for a page: its URI as nginx sees it after try_files, and its policy. */
export function mapLine(uri, policy) {
	if (/["\\$;{}\s]/.test(uri)) throw new Error(`unsupported character in URI ${uri}`);
	// "$" would start an nginx variable, and a double quote or backslash would end the string.
	if (/["\\$]/.test(policy)) throw new Error(`unsupported character in the policy for ${uri}`);
	return `"${uri}" "${policy}";`;
}

function* htmlFiles(dir) {
	for (const name of readdirSync(dir)) {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) yield* htmlFiles(path);
		else if (name.endsWith('.html')) yield path;
	}
}

/** The full map file for a build directory. Every page must carry a policy. */
export function buildMap(buildDir) {
	const lines = [];
	for (const file of [...htmlFiles(buildDir)].sort()) {
		const uri = '/' + relative(buildDir, file).split(sep).join('/');
		const policy = extractPolicy(readFileSync(file, 'utf8'));
		if (!policy) throw new Error(`${uri} has no Content-Security-Policy meta tag`);
		lines.push(mapLine(uri, policy));
	}
	if (lines.length === 0) throw new Error(`no HTML pages in ${buildDir}`);
	return (
		'# Generated by scripts/nginx-csp.mjs from the build. Do not edit.\n' + lines.join('\n') + '\n'
	);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const [buildDir, output] = process.argv.slice(2);
	if (!buildDir || !output) {
		console.error('usage: node scripts/nginx-csp.mjs <build-dir> <output-file>');
		process.exit(2);
	}
	writeFileSync(output, buildMap(buildDir));
	console.log(`wrote ${output}`);
}
